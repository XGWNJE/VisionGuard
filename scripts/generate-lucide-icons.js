// Mechanical conversion of the pinned official SVG subset. Never edit generated outlines.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const vendor = path.join(root, 'assets/vendor/lucide');
const manifest = JSON.parse(fs.readFileSync(path.join(vendor, 'manifest.json'), 'utf8'));
const check = process.argv.includes('--check');
const failures = [];
function output(relative, content) {
  const target = path.join(root, relative);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) failures.push(relative);
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content, 'utf8');
  }
}
function attrs(text) {
  return Object.fromEntries([...text.matchAll(/([\w:-]+)="([^"]*)"/g)].map(m => [m[1], m[2]]));
}
function paths(svg) {
  const frame = attrs(svg.match(/<svg\s+([\s\S]*?)>/)?.[1] ?? '');
  for (const [key, value] of Object.entries({ viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': '2', 'stroke-linecap': 'round', 'stroke-linejoin': 'round' })) {
    if (frame[key] !== value) throw new Error(`Unexpected official SVG style: ${key}`);
  }
  return [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]*?)\s*\/>/g)].map(([, shape, text]) => {
    const a = attrs(text);
    if ('transform' in a || 'fill' in a || 'stroke' in a) throw new Error('Unexpected per-shape SVG style');
    const n = key => Number(a[key] ?? 0);
    if (shape === 'path') return a.d;
    if (shape === 'line') return `M${n('x1')} ${n('y1')}L${n('x2')} ${n('y2')}`;
    if (shape === 'polyline' || shape === 'polygon') return `M${a.points.trim().split(/\s+/).join('L')}${shape === 'polygon' ? 'Z' : ''}`;
    if (shape === 'circle' || shape === 'ellipse') {
      const x = n('cx'), y = n('cy'), rx = shape === 'circle' ? n('r') : n('rx'), ry = shape === 'circle' ? rx : n('ry');
      return `M${x - rx} ${y}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`;
    }
    const x = n('x'), y = n('y'), w = n('width'), h = n('height');
    const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2), ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
    if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x + rx} ${y}H${x + w - rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}V${y + h - ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}H${x + rx}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}V${y + ry}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`;
  });
}
const icons = manifest.icons.map(icon => {
  const bytes = fs.readFileSync(path.join(vendor, 'icons', `${icon.name}.svg`));
  const hash = crypto.createHash('sha256').update(bytes).digest('hex');
  if (hash !== icon.sha256) throw new Error(`Official SVG hash mismatch: ${icon.name}`);
  const data = paths(bytes.toString('utf8'));
  if (!data.length) throw new Error(`Empty official SVG: ${icon.name}`);
  return { ...icon, data };
});
const webPackage = JSON.parse(fs.readFileSync(path.join(root, 'receiver/web/package.json'), 'utf8'));
if (webPackage.dependencies['lucide-react'] !== manifest.version) throw new Error('Lucide versions differ across platforms');
for (const directory of ['android-shared/src/main/java', ...['detector', 'receiver', 'notifier'].map(app => `${app}/android/app/src/main/java`)]) {
  for (const file of fs.readdirSync(path.join(root, directory), { recursive: true }).filter(name => name.endsWith('.kt'))) {
    const source = fs.readFileSync(path.join(root, directory, file), 'utf8');
    if (/import androidx\.compose\.material\.icons\b|setSmallIcon\(R\.mipmap\./.test(source)) throw new Error(`Mixed functional icon family: ${directory}/${file}`);
  }
}
for (const file of ['detector/windows-wpf/Views/MainWindow.xaml', 'detector/windows-wpf/Views/MonitorPage.xaml', 'detector/windows-wpf/Views/GlobalSettingsPage.xaml', 'detector/windows-wpf/Themes/DarkTheme.xaml']) {
  if (/<Path\b/.test(fs.readFileSync(path.join(root, file), 'utf8'))) throw new Error(`Handwritten functional icon path: ${file}`);
}
if (/[✓✔✗✘]/.test(fs.readFileSync(path.join(root, 'detector/windows-wpf/ViewModels/SettingsViewModel.cs'), 'utf8'))) throw new Error('Font character used as a functional model-status icon');
const kotlin = `// Generated by scripts/generate-lucide-icons.js from lucide-static ${manifest.version}.
// ISC + Feather MIT; notices are bundled in assets/third-party/lucide-license.txt.
package com.xgwnje.visionguard.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

object LucideIcons {
${icons.filter(i => i.platforms.includes('android')).map(i => `    val ${i.symbol}: ImageVector by lazy {
        vector("${i.name}", ${i.autoMirror === true}, listOf(
${i.data.map(d => `            ${JSON.stringify(d)}`).join(',\n')}
        ))
    }`).join('\n\n')}

    private fun vector(name: String, autoMirror: Boolean, paths: List<String>): ImageVector =
        ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp,
            viewportWidth = 24f, viewportHeight = 24f, autoMirror = autoMirror).apply {
            paths.forEach { data ->
                addPath(pathData = PathParser().parsePathString(data).toNodes(), fill = null,
                    stroke = SolidColor(Color.Black), strokeLineWidth = 2f,
                    strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)
            }
        }.build()
}
`;
output('android-shared/src/main/java/com/xgwnje/visionguard/icons/LucideIcons.kt', kotlin);
for (const i of icons.filter(i => i.notification)) {
  const xml = `<!-- Generated from lucide-static ${manifest.version}: ${i.name}; ISC + Feather MIT. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
${i.data.map(d => `    <path android:pathData="${d}" android:fillColor="@android:color/transparent"
        android:strokeColor="@android:color/white" android:strokeWidth="2"
        android:strokeLineCap="round" android:strokeLineJoin="round" />`).join('\n')}
</vector>
`;
  output(`android-shared/src/main/res/drawable/ic_lucide_${i.name.replaceAll('-', '_')}.xml`, xml);
}
const windows = icons.filter(i => i.platforms.includes('windows'));
output('detector/windows-wpf/Icons/LucideGeometry.g.cs', `// Generated by scripts/generate-lucide-icons.js from lucide-static ${manifest.version}.
// ISC + Feather MIT; notices are embedded and copied to third-party/lucide-license.txt.
using System.Collections.Generic;
using System.Windows.Media;

namespace VisionGuard.Detector.Windows.Icons
{
    public enum LucideGlyph { ${windows.map(i => i.symbol).join(', ')} }

    internal static class LucideGeometry
    {
        internal static readonly Dictionary<LucideGlyph, Geometry[]> Paths = new Dictionary<LucideGlyph, Geometry[]>
        {
${windows.map(i => `            [LucideGlyph.${i.symbol}] = Parse(${i.data.map(d => JSON.stringify(d)).join(', ')}),`).join('\n')}
        };

        private static Geometry[] Parse(params string[] paths)
        {
            var result = new Geometry[paths.Length];
            for (var i = 0; i < paths.Length; i++) { result[i] = Geometry.Parse(paths[i]); result[i].Freeze(); }
            return result;
        }
    }
}
`);
const notice = `Lucide ${manifest.version}\nSource: ${manifest.source}\n\n${fs.readFileSync(path.join(vendor, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n')}`;
output('android-shared/src/main/assets/third-party/lucide-license.txt', notice);
output('receiver/web/public/third-party/lucide-license.txt', notice);
if (failures.length) throw new Error(`Stale generated Lucide resources:\n${failures.join('\n')}`);
console.log(`Lucide ${manifest.version}: ${icons.length} verified official SVGs; generated resources ${check ? 'checked' : 'updated'}.`);
